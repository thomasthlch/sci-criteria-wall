function rule(id, deduction, source, sourceLabel, text, reason, note = "") {
  return { id, deduction, source, sourceLabel, text, reason, note };
}

function hint(id, keywords, matchedText, deduction, reason, excludeKeywords = []) {
  return { id, keywords, excludeKeywords, matchedText, deduction, reason };
}

function pending(id, text, note, question, demoName, demoDeduction) {
  return {
    id,
    text,
    note,
    question,
    demoLean: { displayName: demoName, deduction: demoDeduction },
  };
}

